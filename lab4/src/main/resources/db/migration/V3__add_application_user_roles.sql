-- Keep existing profile IDs, contact details, and all foreign keys intact.
ALTER TABLE customers
    ADD COLUMN role VARCHAR(20) NOT NULL DEFAULT 'CUSTOMER',
    ADD CONSTRAINT chk_customer_role CHECK (role = 'CUSTOMER');

ALTER TABLE drivers
    ADD COLUMN role VARCHAR(20) NOT NULL DEFAULT 'DRIVER',
    ADD CONSTRAINT chk_driver_role CHECK (role = 'DRIVER');

CREATE TABLE administrators (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(40) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'ADMIN',
    CONSTRAINT chk_administrator_role CHECK (role = 'ADMIN')
);
