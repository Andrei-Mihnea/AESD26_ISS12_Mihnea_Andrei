-- JOINED inheritance: every identity lives in users; profiles retain only their own fields.
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(255) NOT NULL,
    phone VARCHAR(40) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('CUSTOMER', 'DRIVER', 'ADMIN')),
    CONSTRAINT uk_users_role_email UNIQUE (role, email)
);
CREATE UNIQUE INDEX uk_users_driver_phone ON users(phone) WHERE role = 'DRIVER';

-- Customer IDs are public API identifiers and stay unchanged. Allocate all other
-- identities above every legacy ID, avoiding collisions while updating driver PKs.
CREATE TEMP TABLE legacy_user_ids ON COMMIT DROP AS
WITH highest AS (
    SELECT GREATEST(COALESCE((SELECT MAX(id) FROM customers), 0),
                    COALESCE((SELECT MAX(id) FROM drivers), 0),
                    COALESCE((SELECT MAX(id) FROM administrators), 0)) AS id
), profiles AS (
    SELECT 'DRIVER'::VARCHAR(20) AS role, id FROM drivers
    UNION ALL
    SELECT 'ADMIN'::VARCHAR(20) AS role, id FROM administrators
)
SELECT p.role, p.id AS old_id,
       h.id + ROW_NUMBER() OVER (ORDER BY p.role, p.id) AS user_id
FROM profiles p CROSS JOIN highest h;

INSERT INTO users(id, name, email, phone, role)
SELECT id, name, email, phone, 'CUSTOMER' FROM customers;

INSERT INTO users(id, name, email, phone, role)
SELECT m.user_id, d.name, d.email, d.phone, 'DRIVER'
FROM drivers d JOIN legacy_user_ids m ON m.role = 'DRIVER' AND m.old_id = d.id;

INSERT INTO users(id, name, email, phone, role)
SELECT m.user_id, a.name, a.email, a.phone, 'ADMIN'
FROM administrators a JOIN legacy_user_ids m ON m.role = 'ADMIN' AND m.old_id = a.id;

ALTER TABLE vehicles DROP CONSTRAINT vehicles_driver_fkey;
ALTER TABLE drivers ALTER COLUMN id DROP IDENTITY IF EXISTS;
UPDATE drivers d SET id = m.user_id
FROM legacy_user_ids m WHERE m.role = 'DRIVER' AND d.id = m.old_id;
UPDATE vehicles v SET driver = m.user_id
FROM legacy_user_ids m WHERE m.role = 'DRIVER' AND v.driver = m.old_id;
ALTER TABLE vehicles ADD CONSTRAINT vehicles_driver_fkey
    FOREIGN KEY (driver) REFERENCES drivers(id) ON DELETE SET NULL;

ALTER TABLE customers ALTER COLUMN id DROP IDENTITY IF EXISTS;
ALTER TABLE customers DROP COLUMN name, DROP COLUMN email, DROP COLUMN phone, DROP COLUMN role;
ALTER TABLE drivers DROP COLUMN name, DROP COLUMN email, DROP COLUMN phone, DROP COLUMN role;
ALTER TABLE customers ADD CONSTRAINT fk_customers_user
    FOREIGN KEY (id) REFERENCES users(id) ON DELETE CASCADE;
ALTER TABLE drivers ADD CONSTRAINT fk_drivers_user
    FOREIGN KEY (id) REFERENCES users(id) ON DELETE CASCADE;

-- Existing administrator data has been copied above; no administrator-specific table remains.
DROP TABLE administrators;

SELECT setval(pg_get_serial_sequence('users', 'id'),
              COALESCE((SELECT MAX(id) FROM users), 1), EXISTS(SELECT 1 FROM users));
