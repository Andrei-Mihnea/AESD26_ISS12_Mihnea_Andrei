CREATE TABLE IF NOT EXISTS depots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE,
    coordinates VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS drivers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(40) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    depot BIGINT NOT NULL REFERENCES depots(id) ON DELETE RESTRICT,
    available BOOLEAN NOT NULL DEFAULT TRUE,
    driver BIGINT UNIQUE REFERENCES drivers(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(40) NOT NULL,
    address VARCHAR(255) NOT NULL,
    coordinates VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer BIGINT NOT NULL REFERENCES customers(id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    notes TEXT,
    "timestamp" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_vehicles_depot ON vehicles(depot);
CREATE INDEX IF NOT EXISTS idx_deliveries_customer ON deliveries(customer);

CREATE TABLE IF NOT EXISTS scenarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL
);

CREATE TABLE IF NOT EXISTS scenario_vehicles (
    scenario_id BIGINT NOT NULL REFERENCES scenarios(id) ON DELETE CASCADE,
    vehicle_id BIGINT NOT NULL REFERENCES vehicles(id) ON DELETE CASCADE,
    PRIMARY KEY (scenario_id, vehicle_id)
);

CREATE TABLE IF NOT EXISTS scenario_deliveries (
    scenario_id BIGINT NOT NULL REFERENCES scenarios(id) ON DELETE CASCADE,
    delivery_id BIGINT NOT NULL REFERENCES deliveries(id) ON DELETE CASCADE,
    PRIMARY KEY (scenario_id, delivery_id)
);

CREATE INDEX IF NOT EXISTS idx_scenario_vehicles_vehicle ON scenario_vehicles(vehicle_id);
CREATE INDEX IF NOT EXISTS idx_scenario_deliveries_delivery ON scenario_deliveries(delivery_id);
